<?php

/*
 * Prepares the local test environment (run: composer test:setup).
 *  1. Writes .env.testing = .env with the .env.dev overrides, pointed at the shop_majazi_test database.
 *  2. Recreates that database from database/schema/mysql-schema.sql (structure only, no data).
 * Refresh the schema file after a schema change with:
 *  mysqldump --no-data --skip-comments --skip-add-drop-table shop_majazi_dev > database/schema/mysql-schema.sql
 */

$root = dirname(__DIR__);
$testDb = 'shop_majazi_test';

$read = function (string $file): array {
    $vars = [];
    foreach (@file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $line) {
        if ($line[0] === '#' || !str_contains($line, '=')) {
            continue;
        }
        [$k, $v] = array_map('trim', explode('=', $line, 2));
        $vars[$k] = $v;
    }
    return $vars;
};

$env = array_merge($read("$root/.env"), $read("$root/.env.dev"), [
    'APP_ENV' => 'testing',
    'DB_DATABASE' => $testDb,
    'DEV_FAKE_PROVIDERS' => 'true',
]);
file_put_contents("$root/.env.testing", "# Generated by tests/setup-test-db.php. Do not edit; rerun composer test:setup.\n"
    . implode("\n", array_map(fn ($k, $v) => "$k=$v", array_keys($env), $env)) . "\n");
echo "Wrote .env.testing\n";

$dsn = sprintf('mysql:host=%s;port=%s;charset=utf8mb4', $env['DB_HOST'] ?? '127.0.0.1', $env['DB_PORT'] ?? '3306');
$pdo = new PDO($dsn, $env['DB_USERNAME'] ?? 'root', $env['DB_PASSWORD'] ?? '', [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$pdo->exec("DROP DATABASE IF EXISTS `$testDb`");
$pdo->exec("CREATE DATABASE `$testDb` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
$pdo->exec("USE `$testDb`");
$pdo->exec(file_get_contents("$root/database/schema/mysql-schema.sql"));
$tables = $pdo->query("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = '$testDb'")->fetchColumn();
echo "Recreated $testDb with $tables tables\n";
